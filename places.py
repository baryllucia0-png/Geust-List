locations=['America','Dubai','France','Brazil','Canada']
print(locations)

#sorting in alphabetical order
locations.sort()
print(locations)

#sorting in reverse order
locations.sort(reverse=True)
print(locations)

#reversing back to original order
locations.reverse()
print(locations)

#reversing to change the order
locations.reverse()
print(locations)

#sorting to change list
locations.sort()
print(locations)

#sorting to change list to reverse order
locations.sort(reverse=True)
print(locations)